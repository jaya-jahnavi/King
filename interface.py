"""Simple live dashboard; configuration and correction tools live on separate tabs."""
import tkinter as tk
from tkinter import ttk
from counting import RANKS
from openai_vision import DEFAULT_MODEL


def build_ui(app):
    window = app.window
    window.title('King — live count & rounds')
    width = min(1160, max(980, window.winfo_screenwidth()-60))
    height = min(900, max(640, window.winfo_screenheight()-70))
    window.geometry(f'{width}x{height}')
    window.minsize(980, min(720, height))
    style = ttk.Style(window)
    style.theme_use('clam')
    style.configure('.', font=('Segoe UI', 10))
    style.configure('TFrame', background='#f3f5f9')
    style.configure('TLabel', background='#f3f5f9', foreground='#233047')
    style.configure('Card.TFrame', background='white')
    style.configure('Card.TLabel', background='white', foreground='#526078')
    style.configure('Value.TLabel', background='white', foreground='#17365b', font=('Segoe UI', 28, 'bold'))
    style.configure('Accent.TButton', background='#205acf', foreground='white', padding=(16, 10))
    style.map('Accent.TButton', background=[('active', '#1746a7')])
    style.configure('TButton', padding=(10, 7))
    style.configure('Danger.TButton', foreground='#a52635')
    style.configure('Treeview', rowheight=29, font=('Segoe UI', 10))
    style.configure('Treeview.Heading', font=('Segoe UI', 10, 'bold'))
    header = ttk.Frame(window, padding=(18, 12))
    header.pack(fill='x')
    ttk.Label(header, text='KING', font=('Segoe UI', 19, 'bold')).pack(side='left')
    ttk.Label(header, text='Live card count · saved by round', padding=(16, 0)).pack(side='left')
    ttk.Button(header, text='Clear data / Start Round 1', style='Danger.TButton', command=app.clear_data).pack(side='right')
    app.start_label = tk.StringVar(value='3  Start counting')
    app.activity = tk.StringVar(value='Paused · choose your video to begin')
    app.history_note = tk.StringVar(value='Round history saves automatically on this computer.')
    app.running_value = tk.StringVar(value='+0')
    app.round_value = tk.StringVar(value='+0')
    app.round_badge = tk.StringVar(value='Round 1')
    app.cards_value = tk.StringVar(value='0')
    app.round_details = tk.StringVar(value='Round 1\nWaiting for cards')
    app.mode_hint = tk.StringVar()
    app.capture_info = tk.StringVar()
    app.calibration_info = tk.StringVar()
    app.calibration_message = tk.StringVar(value='Choose a video area first, then add a tight box around a visible card rank.')
    app.notebook = ttk.Notebook(window)
    app.notebook.pack(fill='both', expand=True, padx=14, pady=(0, 12))
    live, settings, corrections, calibration = (ttk.Frame(app.notebook, padding=12) for _ in range(4))
    app.calibration_tab = calibration
    for tab, name in [(live, 'Live count'), (settings, 'Settings'), (corrections, 'Corrections'), (calibration, 'Card positions')]:
        app.notebook.add(tab, text=name)
    live.columnconfigure(0, weight=1)
    live.rowconfigure(4, weight=2)
    live.rowconfigure(5, weight=1)
    setup = ttk.Frame(live)
    setup.grid(row=0, column=0, sticky='ew', pady=(0, 10))
    ttk.Button(setup, text='1  Connect OpenAI', command=app.set_api_key).pack(side='left', padx=(0, 8))
    ttk.Label(setup, text='Video screen:').pack(side='left')
    app.monitor_names = app.display_names()
    app.monitor_choice = ttk.Combobox(setup, values=app.monitor_names, state='readonly', width=36)
    app.monitor_choice.current(0)
    app.monitor_choice.pack(side='left', padx=6)
    app.monitor_choice.bind('<<ComboboxSelected>>', app.change_display)
    ttk.Button(setup, text='2  Choose video area', command=app.select_table).pack(side='left', padx=6)
    ttk.Button(setup, textvariable=app.start_label, style='Accent.TButton', command=app.toggle).pack(side='right')
    actions = ttk.Frame(live)
    actions.grid(row=1, column=0, sticky='ew', pady=(0, 10))
    ttk.Button(actions, text='Next round', command=app.next_round).pack(side='left', padx=(0, 6))
    ttk.Button(actions, text='New shoe', command=app.shuffle).pack(side='left', padx=6)
    ttk.Button(actions, text='Export rounds CSV', command=app.export).pack(side='left', padx=6)
    ttk.Label(actions, text='Count speed:').pack(side='left', padx=(18, 4))
    speed = ttk.Combobox(actions, textvariable=app.speed, values=['Fast (1 read)', 'Verified (2 reads)'], width=18, state='readonly')
    speed.pack(side='left')
    speed.bind('<<ComboboxSelected>>', app.change_speed)
    ttk.Label(actions, textvariable=app.mode_hint, padding=(10, 0)).pack(side='left')
    metrics = ttk.Frame(live)
    metrics.grid(row=2, column=0, sticky='ew', pady=(0, 8))
    for i, (label, variable) in enumerate([('RUNNING COUNT', app.running_value), ('THIS ROUND', app.round_value),
                                          ('CURRENT ROUND', app.round_badge), ('CARDS THIS ROUND', app.cards_value)]):
        metrics.columnconfigure(i, weight=1)
        card = ttk.Frame(metrics, style='Card.TFrame', padding=(14, 9))
        card.grid(row=0, column=i, sticky='nsew', padx=(0, 8) if i<3 else 0)
        ttk.Label(card, text=label, style='Card.TLabel', font=('Segoe UI', 9, 'bold')).pack(anchor='w')
        ttk.Label(card, textvariable=variable, style='Value.TLabel').pack(anchor='w')
    notice = ttk.Frame(live)
    notice.grid(row=3, column=0, sticky='ew', pady=(0, 8))
    ttk.Label(notice, textvariable=app.activity, font=('Segoe UI', 11, 'bold')).pack(anchor='w')
    ttk.Label(notice, textvariable=app.status, wraplength=1060).pack(anchor='w', pady=(3, 0))
    body = ttk.Frame(live)
    body.grid(row=4, column=0, sticky='nsew', pady=(0, 8))
    body.columnconfigure(0, weight=3)
    body.columnconfigure(1, weight=2)
    body.rowconfigure(0, weight=1)
    app.preview = ttk.Label(body, text='Your selected video appears here', anchor='center', background='#e5eaf2')
    app.preview.grid(row=0, column=0, sticky='nsew', padx=(0, 12))
    details = ttk.Frame(body, style='Card.TFrame', padding=14)
    details.grid(row=0, column=1, sticky='nsew')
    ttk.Label(details, text='ROUND CARDS', style='Card.TLabel', font=('Segoe UI', 10, 'bold')).pack(anchor='w')
    detail_body = ttk.Frame(details, style='Card.TFrame')
    detail_body.pack(fill='both', expand=True, pady=10)
    detail_text = tk.Text(detail_body, width=28, height=4, wrap='word', font=('Segoe UI', 12),
                          background='white', foreground='#526078', relief='flat', state='disabled')
    detail_scroll = ttk.Scrollbar(detail_body, orient='vertical', command=detail_text.yview)
    detail_scroll.pack(side='right', fill='y')
    detail_text.configure(yscrollcommand=detail_scroll.set)
    detail_text.pack(side='left', fill='both', expand=True)
    def update_details(*args):
        detail_text.configure(state='normal')
        detail_text.delete('1.0', 'end')
        detail_text.insert('1.0', app.round_details.get())
        detail_text.configure(state='disabled')
    app.round_details.trace_add('write', update_details)
    ttk.Label(details, text='Select a saved round below to review it.', style='Card.TLabel', wraplength=300).pack(anchor='w', side='bottom')
    history = ttk.Frame(live)
    history.grid(row=5, column=0, sticky='nsew')
    history.columnconfigure(0, weight=1)
    history.rowconfigure(1, weight=1)
    edit = ttk.Frame(history)
    edit.grid(row=0, column=0, columnspan=2, sticky='ew', pady=(0, 5))
    ttk.Label(edit, text='Missed a card?').pack(side='left', padx=(0, 8))
    ttk.Button(edit, text='Add to selected round', command=app.add_missed_card).pack(side='left', padx=4)
    ttk.Button(edit, text='Add to previous round', command=lambda: app.add_missed_card(previous=True)).pack(side='left', padx=4)
    columns = ('shoe', 'round', 'cards', 'delta', 'running', 'state')
    app.round_table = ttk.Treeview(history, columns=columns, show='headings', height=6, selectmode='browse')
    for column, label, width in [('shoe','Shoe',55),('round','Round',90),('cards','Cards recognized',430),
                                  ('delta','Round count',125),('running','Running count',140),('state','Status',110)]:
        app.round_table.heading(column, text=label)
        app.round_table.column(column, width=width, minwidth=45, stretch=column=='cards')
    app.round_table.grid(row=1, column=0, sticky='nsew')
    scroll = ttk.Scrollbar(history, orient='vertical', command=app.round_table.yview)
    scroll.grid(row=1, column=1, sticky='ns')
    app.round_table.configure(yscrollcommand=scroll.set)
    app.round_table.bind('<<TreeviewSelect>>', app.show_round)
    ttk.Label(live, textvariable=app.history_note, wraplength=1050).grid(row=6, column=0, sticky='w', pady=(6, 0))
    ttk.Label(settings, text='Recognition & connection', font=('Segoe UI', 15, 'bold')).pack(anchor='w', pady=(0, 10))
    row = ttk.Frame(settings)
    row.pack(fill='x', pady=6)
    ttk.Label(row, text='Reader:').pack(side='left')
    provider = ttk.Combobox(row, textvariable=app.backend, values=['OpenAI', 'Local OCR'], state='readonly', width=14)
    provider.pack(side='left', padx=8)
    provider.bind('<<ComboboxSelected>>', app.change_provider)
    model = ttk.Combobox(row, textvariable=app.api_model, values=[DEFAULT_MODEL,'gpt-6.1-sol','gpt-6-astra','gpt-6-luna'], state='readonly', width=20)
    model.pack(side='left', padx=8)
    model.bind('<<ComboboxSelected>>', app.change_mode)
    ttk.Button(row, text='Set API key', command=app.set_api_key).pack(side='left', padx=8)
    row = ttk.Frame(settings)
    row.pack(fill='x', pady=8)
    ttk.Label(row, text='Minimum seconds between requests:').pack(side='left')
    ttk.Spinbox(row, from_=1, to=30, textvariable=app.api_interval, width=5).pack(side='left', padx=8)
    ttk.Label(row, text='Session request limit:').pack(side='left', padx=(16, 4))
    ttk.Spinbox(row, from_=1, to=1000, textvariable=app.api_limit, width=6).pack(side='left', padx=8)
    ttk.Button(settings, text='Test recording — 1 paid request', command=app.test_recording).pack(anchor='w', pady=8)
    ttk.Label(settings, textvariable=app.api_info, wraplength=1000).pack(anchor='w', pady=8)
    ttk.Label(settings, textvariable=app.capture_info, wraplength=1000).pack(anchor='w', pady=8)
    ttk.Button(settings, text='Refresh screens', command=app.refresh_displays).pack(anchor='w', pady=8)
    ttk.Label(settings, textvariable=app.stats, wraplength=1000).pack(anchor='w', pady=8)
    ttk.Separator(settings).pack(fill='x', pady=12)
    ttk.Label(settings, text='Manual card-position setup is in the Card positions tab. OpenAI reads do not use position boxes.').pack(anchor='w')
    ttk.Button(settings, text='Open card-position setup', command=lambda: app.notebook.select(calibration)).pack(anchor='w', pady=8)
    ttk.Label(calibration, text='Manual card positions', font=('Segoe UI', 15, 'bold')).pack(anchor='w', pady=8)
    ttk.Label(calibration, text='For the local template reader. OpenAI does not use these boxes.\n'
                                'Adding a position switches to manual reading; the app pauses while you configure it.', wraplength=1000).pack(anchor='w', pady=6)
    row = ttk.Frame(calibration)
    row.pack(fill='x')
    ttk.Button(row, text='Choose video area', command=app.select_table).pack(side='left', padx=4)
    ttk.Button(row, text='Add card position', command=app.add_slot).pack(side='left', padx=4)
    ttk.Button(row, text='Save rank template', command=app.template).pack(side='left', padx=4)
    ttk.Button(row, text='Use these positions', command=app.use_positions).pack(side='left', padx=4)
    ttk.Button(row, text='Show on live preview', command=lambda: app.notebook.select(0)).pack(side='left', padx=4)
    ttk.Label(calibration, textvariable=app.calibration_message, wraplength=1000, font=('Segoe UI', 10, 'bold')).pack(anchor='w', pady=10)
    ttk.Label(calibration, textvariable=app.calibration_info, wraplength=1000).pack(anchor='w', pady=6)
    app.position_table = ttk.Treeview(calibration, columns=('position','x','y','width','height'), show='headings', height=6, selectmode='browse')
    for key, label in [('position','Position'),('x','X'),('y','Y'),('width','Width'),('height','Height')]:
        app.position_table.heading(key, text=label)
        app.position_table.column(key, width=100, stretch=True)
    app.position_table.pack(fill='x', pady=8)
    ttk.Button(calibration, text='Remove selected position', command=app.remove_slot).pack(anchor='w', pady=6)
    row = ttk.Frame(calibration)
    row.pack(fill='x', pady=10)
    ttk.Checkbutton(row, text='Automatic reading (positions used only when off)', variable=app.auto, command=app.change_mode).pack(side='left', padx=4)
    ttk.Label(row, text=' Match threshold:').pack(side='left')
    ttk.Spinbox(row, from_=0.7, to=0.99, increment=.01, textvariable=app.threshold, width=6).pack(side='left')
    ttk.Label(corrections, text='Correct an observation', font=('Segoe UI', 15, 'bold')).pack(anchor='w', pady=8)
    ttk.Label(corrections, text='Undo pauses counting. Replace a mistaken card with the right rank. Manual additions can duplicate automatic reads.').pack(anchor='w', pady=8)
    ttk.Button(corrections, text='Undo last card', command=app.undo).pack(anchor='w', pady=8)
    row = ttk.Frame(corrections)
    row.pack(anchor='w', pady=8)
    for i, rank in enumerate(RANKS):
        ttk.Button(row, text=rank, width=5, command=lambda r=rank: app.manual(r)).grid(row=i//7, column=i%7, padx=4, pady=4)
    app.log = tk.Listbox(corrections, font=('Consolas', 11), height=12)
    app.log.pack(fill='both', expand=True, pady=10)
